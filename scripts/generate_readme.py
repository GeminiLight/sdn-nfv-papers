#!/usr/bin/env python3
"""Generate README.md and its visualizations from the canonical paper CSV."""

from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path
from urllib.parse import urlparse

sys.dont_write_bytecode = True
from catalog import CATEGORIES, DIRECTIONS, ValidationError, load_catalog, primary_value, split_values


ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
HEADER_PATH = DATA_DIR / "README.header.md"
FOOTER_PATH = DATA_DIR / "README.footer.md"
VISUALIZATION_DIR = ROOT / "visualization"
VISUALIZATION_SCRIPT = VISUALIZATION_DIR / "generate_visualizations.py"
SITE_SCRIPT = ROOT / "scripts" / "generate_site.py"
ANALYSIS_PATH = VISUALIZATION_DIR / "analysis.md"
OUTPUT_PATH = ROOT / "README.md"

VISIBLE_PAPERS_PER_GROUP = 20

NOTICE = """<!--
This file is generated by scripts/generate_readme.py from:
- data/README.header.md
- data/papers.csv
- data/taxonomy.csv
- data/provenance.csv
- data/venues.csv
- visualization/analysis.md
- data/README.footer.md

Do not edit README.md directly. Edit one of the source files and regenerate it.
-->"""


def markdown_anchor(label: str) -> str:
    anchor = label.lower().replace(".", "")
    anchor = re.sub(r"[^a-z0-9 -]", "", anchor)
    return re.sub(r"[ -]+", "-", anchor).strip("-")


def escape_markdown(value: str) -> str:
    return value.replace("\\", "\\\\").replace("*", "\\*").replace("[", "\\[").replace("]", "\\]")


def link_label(url: str, *, primary: bool = False, paper_id: str = "") -> str:
    host = urlparse(url).netloc.lower().removeprefix("www.")
    path = urlparse(url).path.lower()
    if primary:
        return "arXiv" if paper_id.startswith("arxiv:") else "DOI"
    if "doi.org" in host:
        return "published version" if paper_id.startswith("arxiv:") else "related DOI"
    if "researchgate.net" in host:
        return "ResearchGate"
    if "dl.acm.org" in host:
        return "ACM DL"
    if path.endswith(".pdf") or "/pdf" in path or "document" in path:
        return "PDF"
    return host or "other"


def render_links(paper: dict[str, str]) -> str:
    links: list[tuple[str, str]] = [
        (link_label(paper["paper_url"], primary=True, paper_id=paper["paper_id"]), paper["paper_url"])
    ]
    if paper["code_url"]:
        links.append(("code", paper["code_url"]))
    if paper["data_url"]:
        links.append(("data", paper["data_url"]))
    for url in split_values(paper["other_urls"]):
        links.append((link_label(url, paper_id=paper["paper_id"]), url))

    totals = Counter(label for label, _ in links)
    seen: Counter[str] = Counter()
    rendered: list[str] = []
    for label, url in links:
        seen[label] += 1
        display_label = f"{label} {seen[label]}" if totals[label] > 1 else label
        rendered.append(f"[{display_label}]({url})")
    return ", ".join(rendered)


def render_paper(paper: dict[str, str]) -> str:
    publication = f"{paper['venue']} {paper['year']}"
    if paper["ranks"]:
        publication += f" (**{escape_markdown(paper['ranks'])}**)"

    lines = [
        f"1. **{escape_markdown(paper['title'])}**",
        f"   - `Publication`: {publication}",
        f"   - `Authors`: {escape_markdown(paper['authors'])}",
    ]
    if paper["keywords"]:
        lines.append(f"   - `Keywords`: {escape_markdown(paper['keywords'])}")
    if paper["objectives"]:
        lines.append(f"   - `Objective`: {escape_markdown(paper['objectives'])}")
    lines.append(f"   - `Link`: {render_links(paper)}")
    return "\n".join(lines)


def paper_sort_key(paper: dict[str, str]) -> tuple[int, str, str, str]:
    return (-int(paper["year"]), paper["title"].casefold(), paper["venue"].casefold(), paper["paper_id"])


def render_group(papers: list[dict[str, str]]) -> str:
    papers = sorted(papers, key=paper_sort_key)
    visible = papers[:VISIBLE_PAPERS_PER_GROUP]
    earlier = papers[VISIBLE_PAPERS_PER_GROUP:]
    blocks = [render_paper(paper) for paper in visible]
    if earlier:
        blocks.extend(
            [
                f"<details>\n<summary>Earlier papers ({len(earlier)})</summary>",
                "\n\n".join(render_paper(paper) for paper in earlier),
                "</details>",
            ]
        )
    return "\n\n".join(blocks)


def group_papers(papers: list[dict[str, str]]) -> dict[str, dict[str, list[dict[str, str]]]]:
    grouped: dict[str, dict[str, list[dict[str, str]]]] = defaultdict(lambda: defaultdict(list))
    category_has_subsections = {key: has_subsections for key, _, has_subsections in CATEGORIES}
    for paper in papers:
        category = primary_value(paper["categories"])
        direction = primary_value(paper["directions"]) if category_has_subsections[category] else ""
        grouped[category][direction].append(paper)
    return grouped


def render_catalog(papers: list[dict[str, str]]) -> str:
    grouped = group_papers(papers)
    statuses = Counter(paper["verification_status"] for paper in papers)
    provenance_summary = ", ".join(
        f"{count} {status.replace('_', ' ')}" for status, count in sorted(statuses.items())
    )
    lines = [
        "## Content",
        "",
        f"> Generated from the catalog data: **{len(papers)} curated paper records** ({provenance_summary}).",
        "",
    ]

    for category_key, category_label, has_subsections in CATEGORIES:
        lines.append(f"- [{category_label}](#{markdown_anchor(category_label)})")
        if has_subsections:
            for direction_key, number, direction_label in DIRECTIONS:
                if grouped[category_key].get(direction_key):
                    subsection_label = f"{category_label.split('.', 1)[0]}.{number} {direction_label}"
                    lines.append(f"  - [{subsection_label}](#{markdown_anchor(subsection_label)})")

    for category_key, category_label, has_subsections in CATEGORIES:
        lines.extend(["", f"## [{category_label}](#content)", ""])
        if has_subsections:
            for direction_key, number, direction_label in DIRECTIONS:
                group = grouped[category_key].get(direction_key, [])
                if not group:
                    continue
                subsection_label = f"{category_label.split('.', 1)[0]}.{number} {direction_label}"
                lines.extend([f"### [{subsection_label}](#content)", "", render_group(group), ""])
        else:
            lines.extend([render_group(grouped[category_key].get("", [])), ""])

    return "\n".join(lines).rstrip()


def build_readme() -> tuple[str, int]:
    papers = load_catalog().papers
    header = HEADER_PATH.read_text(encoding="utf-8").strip()
    analysis = ANALYSIS_PATH.read_text(encoding="utf-8").strip()
    footer = FOOTER_PATH.read_text(encoding="utf-8").strip()
    catalog = render_catalog(papers)
    return f"{NOTICE}\n\n{header}\n\n{analysis}\n\n{catalog}\n\n{footer}\n", len(papers)


def refresh_visualizations(check: bool) -> int:
    command = [sys.executable, "-B", str(VISUALIZATION_SCRIPT)]
    if check:
        command.append("--check")
    try:
        result = subprocess.run(command, cwd=ROOT, check=False)
    except OSError as error:
        print(f"error: unable to run visualization generator: {error}", file=sys.stderr)
        return 2
    return result.returncode


def refresh_site_data(check: bool) -> int:
    command = [sys.executable, "-B", str(SITE_SCRIPT)]
    if check:
        command.append("--check")
    try:
        result = subprocess.run(command, cwd=ROOT, check=False)
    except OSError as error:
        print(f"error: unable to run website data generator: {error}", file=sys.stderr)
        return 2
    return result.returncode


def check_output(expected: str) -> int:
    actual = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
    if actual == expected:
        print(f"{OUTPUT_PATH.name} is up to date")
        return 0

    print(f"{OUTPUT_PATH.name} is out of date; run: python3 scripts/generate_readme.py", file=sys.stderr)
    diff = difflib.unified_diff(
        actual.splitlines(),
        expected.splitlines(),
        fromfile=str(OUTPUT_PATH),
        tofile="generated README",
        lineterm="",
    )
    for index, line in enumerate(diff):
        if index >= 80:
            print("... diff truncated ...", file=sys.stderr)
            break
        print(line, file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated artifacts are not up to date")
    args = parser.parse_args()

    visualization_status = refresh_visualizations(args.check)
    if visualization_status:
        return visualization_status

    site_status = refresh_site_data(args.check)
    if site_status:
        return site_status

    try:
        content, paper_count = build_readme()
    except (OSError, ValidationError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if args.check:
        return check_output(content)

    OUTPUT_PATH.write_text(content, encoding="utf-8")
    print(f"generated {OUTPUT_PATH.name} from {paper_count} paper records")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
