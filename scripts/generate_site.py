#!/usr/bin/env python3
"""Generate browser and crawler-friendly artifacts for the static paper website."""

from __future__ import annotations

import argparse
import difflib
import html
import json
import sys
from collections import defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
SITE_URL = "https://tianfuwang.tech/sdn-nfv-papers/"
OUTPUT_PATHS = {
    "catalog": ROOT / "assets" / "papers.js",
    "static": ROOT / "papers.html",
    "sitemap": ROOT / "sitemap.xml",
    "robots": ROOT / "robots.txt",
}
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "scripts"))

from catalog import ValidationError, load_catalog  # noqa: E402


def render_javascript(papers: list[dict[str, str]]) -> str:
    payload = {
        "source": ["data/papers.csv", "data/taxonomy.csv", "data/provenance.csv", "data/venues.csv"],
        "count": len(papers),
        "papers": papers,
    }
    encoded = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    return (
        "// Generated by scripts/generate_site.py from the catalog CSV sources.\n"
        "// Do not edit this file directly.\n"
        f"window.PAPER_CATALOG={encoded};\n"
    )


def render_static_catalog(papers: list[dict[str, str]]) -> str:
    by_year: dict[int, list[dict[str, str]]] = defaultdict(list)
    for paper in papers:
        by_year[int(paper["year"])].append(paper)

    sections: list[str] = []
    for year in sorted(by_year, reverse=True):
        items: list[str] = []
        for paper in sorted(by_year[year], key=lambda item: (item["title"].casefold(), item["paper_id"])):
            rank = f" / {html.escape(paper['ranks'])}" if paper["ranks"] else ""
            items.append(
                "\n".join(
                    [
                        '        <li class="paper-item">',
                        f'          <div class="paper-index"><strong>{year}</strong>{html.escape(paper["venue"])}{rank}</div>',
                        "          <div>",
                        f'            <a class="paper-title" href="{html.escape(paper["paper_url"], quote=True)}">{html.escape(paper["title"])}</a>',
                        f'            <p class="paper-authors">{html.escape(paper["authors"].replace("; ", ", "))}</p>',
                        "          </div>",
                        "        </li>",
                    ]
                )
            )
        sections.extend(
            [
                f'      <h2 class="static-year-heading" id="year-{year}">{year}</h2>',
                '      <ol class="paper-list">',
                "\n".join(items),
                "      </ol>",
            ]
        )

    description = "A static, indexable list of papers in the curated SDN/NFV network resource allocation catalog."
    return f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="description" content="{description}">
    <title>All papers · SDN/NFV Paper Index</title>
    <link rel="canonical" href="{SITE_URL}papers.html">
    <link rel="stylesheet" href="assets/site.css">
    <link rel="stylesheet" href="assets/brand.css">
    <link rel="stylesheet" href="assets/details.css">
    <link rel="stylesheet" href="assets/responsive.css">
  </head>
  <body class="static-catalog-page">
    <header class="site-header">
      <nav class="nav-shell" aria-label="Primary navigation">
        <a class="wordmark" href="./" aria-label="SDN/NFV Paper Index home"><span class="wordmark-mark" aria-hidden="true"></span><span class="wordmark-copy"><span class="wordmark-name">SDN/NFV</span><span class="wordmark-divider" aria-hidden="true"></span><span class="wordmark-descriptor">Paper Index</span></span></a>
        <div class="nav-links"><a href="./">Interactive catalog</a><a href="data/papers.csv">Source CSV</a></div>
      </nav>
    </header>
    <main class="shell static-catalog-main">
      <div class="static-catalog-heading">
        <p class="eyebrow">Static paper index</p>
        <h1>All {len(papers)} papers.</h1>
        <p>{description} Use the <a href="./">interactive catalog</a> for full-text search, filters, exports, and paper details.</p>
      </div>
{chr(10).join(sections)}
    </main>
  </body>
</html>
"""


def build_outputs() -> tuple[dict[Path, str], int]:
    papers = load_catalog().papers
    outputs = {
        OUTPUT_PATHS["catalog"]: render_javascript(papers),
        OUTPUT_PATHS["static"]: render_static_catalog(papers),
        OUTPUT_PATHS["sitemap"]: (
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            f"  <url><loc>{SITE_URL}</loc></url>\n"
            f"  <url><loc>{SITE_URL}papers.html</loc></url>\n"
            "</urlset>\n"
        ),
        OUTPUT_PATHS["robots"]: f"User-agent: *\nAllow: /\nSitemap: {SITE_URL}sitemap.xml\n",
    }
    return outputs, len(papers)


def check_outputs(outputs: dict[Path, str]) -> int:
    stale = [path for path, content in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != content]
    if not stale:
        print("website artifacts are up to date")
        return 0

    for path in stale:
        actual = path.read_text(encoding="utf-8") if path.exists() else ""
        print(f"{path.relative_to(ROOT)} is out of date; run: python3 scripts/generate_site.py", file=sys.stderr)
        for index, line in enumerate(
            difflib.unified_diff(
                actual.splitlines(),
                outputs[path].splitlines(),
                fromfile=str(path.relative_to(ROOT)),
                tofile=f"generated {path.name}",
                lineterm="",
            )
        ):
            if index >= 20:
                print("... diff truncated ...", file=sys.stderr)
                break
            print(line, file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated website artifacts are stale")
    args = parser.parse_args()

    try:
        outputs, paper_count = build_outputs()
    except (OSError, ValidationError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if args.check:
        return check_outputs(outputs)

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print(f"generated {len(outputs)} website artifacts from {paper_count} paper records")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
