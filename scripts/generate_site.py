#!/usr/bin/env python3
"""Generate the browser-ready paper catalog used by the static website."""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
OUTPUT_PATH = ROOT / "assets" / "papers.js"
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "scripts"))

from generate_readme import ValidationError, load_papers  # noqa: E402


def build_catalog() -> tuple[str, int]:
    papers = load_papers()
    payload = {
        "source": "data/papers.csv",
        "count": len(papers),
        "papers": papers,
    }
    encoded = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    return (
        "// Generated by scripts/generate_site.py from data/papers.csv.\n"
        "// Do not edit this file directly.\n"
        f"window.PAPER_CATALOG={encoded};\n",
        len(papers),
    )


def check_output(expected: str) -> int:
    actual = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
    if actual == expected:
        print(f"{OUTPUT_PATH.relative_to(ROOT)} is up to date")
        return 0

    print(
        f"{OUTPUT_PATH.relative_to(ROOT)} is out of date; run: python3 scripts/generate_site.py",
        file=sys.stderr,
    )
    diff = difflib.unified_diff(
        actual.splitlines(),
        expected.splitlines(),
        fromfile=str(OUTPUT_PATH.relative_to(ROOT)),
        tofile="generated site catalog",
        lineterm="",
    )
    for index, line in enumerate(diff):
        if index >= 30:
            print("... diff truncated ...", file=sys.stderr)
            break
        print(line, file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated catalog is stale")
    args = parser.parse_args()

    try:
        content, paper_count = build_catalog()
    except (OSError, ValidationError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if args.check:
        return check_output(content)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(content, encoding="utf-8")
    print(f"generated {OUTPUT_PATH.relative_to(ROOT)} from {paper_count} paper records")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
